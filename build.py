#!/usr/bin/env python3
"""Render site/index.html from template.html and scanners.json (standard library only).

    python3 build.py           # writes site/index.html
    python3 build.py --check   # exit 1 if site/index.html is out of date
"""
import datetime
import hashlib
import html
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
esc = html.escape


def colors_css(scanners):
    """Each scanner's colours as CSS variables. A separate file, because the page's
    Content-Security-Policy (style-src 'self') blocks inline style attributes."""
    out = ["/* generated by build.py from scanners.json - don't edit */"]
    for s in scanners:
        c = s["colors"]
        out.append(f'[data-scanner="{s["name"]}"] {{ --top: {c["top"]}; --card: {c["card"]}; '
                   f'--border: {c["border"]}; --accent: {c["accent"]}; --on-accent: {c["on_accent"]}; '
                   f'--ink: {c["ink"]}; --soft: {c["soft"]}; }}')
    return "\n".join(out) + "\n"


def tile(s):
    cves = s["cves"]
    links = [f'<a href="https://nvd.nist.gov/vuln/detail/{esc(cves[0])}" rel="noopener">{esc(cves[0])}</a>']
    for cve in cves[1:]:   # CVE-2026-109619 -> "-109619" when the year matches
        short = "-" + cve.rsplit("-", 1)[1] if cve.rsplit("-", 1)[0] == cves[0].rsplit("-", 1)[0] else cve
        links.append(f'<a href="https://nvd.nist.gov/vuln/detail/{esc(cve)}" rel="noopener">{esc(short)}</a>')
    since = datetime.date.fromisoformat(s["since"]).strftime("%-d %b %Y")
    bars = "".join('<span class="on"></span>' if i < s["level"] else "<span></span>" for i in range(5))
    note = f' <span class="vuln-note">{esc(s["vuln_note"])}</span>' if s.get("vuln_note") else ""
    rest = s["name"][len(s["prefix"]) + 1:]
    level_cls = "crit" if s["level"] >= 5 else "high"
    data = (f'data-scanner="{esc(s["name"])}" data-vuln="{esc(s["vuln"])}" data-url="{esc(s["url"])}" '
            f'data-since="{esc(s["since"])}" data-cvss="{s["cvss"]}" data-exploited="{1 if s["exploited"] else 0}"')
    return f'''      <article class="tile sev-{level_cls}" {data}>
        <div class="tile-top">
          <p class="tile-mark"><span>{esc(s["prefix"])}</span><span class="wm-2">2</span><span class="wm-scan">{esc(rest)}</span></p>
          {s["art"]}
        </div>
        <div class="tile-body">
          <h3>{esc(s["vuln"])}{note}</h3>
          <p class="cves">{(", ".join(links[:-1]) + " and " + links[-1]) if len(links) > 1 else links[0]}</p>
          <p>{esc(s["summary"])}</p>
          <div class="severity">
            <span class="bars" role="img" aria-label="Panic level {s["level"]} of 5">{bars}</span>
            <strong>{esc(s["severity"])}</strong><span>CVSS {s["cvss"]}</span><span>since {since}</span>
          </div>
          <a class="check" href="{esc(s["url"])}">Check your site<span class="sr-only"> for {esc(s["vuln"])}</span></a>
        </div>
      </article>'''


def build():
    data = json.load(open(os.path.join(HERE, "scanners.json"), encoding="utf-8"))
    scanners = data["scanners"]
    css = open(os.path.join(HERE, "site", "style.css"), "rb").read()
    js = open(os.path.join(HERE, "site", "app.js"), "rb").read()
    page = open(os.path.join(HERE, "template.html"), encoding="utf-8").read()
    colors = colors_css(scanners)
    repo_links = "".join(f'<a href="{esc(s["github"])}" rel="noopener">{esc(s["name"])} on GitHub</a>'
                         for s in scanners)
    return (page.replace("{{TILES}}", "\n".join(tile(s) for s in scanners))
                .replace("{{REPO_LINKS}}", repo_links)
                .replace("{{FIRST}}", scanners[0]["name"])
                .replace("{{CSS_VERSION}}", hashlib.sha256(css).hexdigest()[:10])
                .replace("{{JS_VERSION}}", hashlib.sha256(js).hexdigest()[:10])
                .replace("{{COLORS_VERSION}}", hashlib.sha256(colors.encode()).hexdigest()[:10])), colors


def main():
    page, colors = build()
    files = {os.path.join(HERE, "site", "index.html"): page,
             os.path.join(HERE, "site", "scanners.css"): colors}
    if "--check" in sys.argv:
        for path, text in files.items():
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if current != text:
                print(f"{os.path.relpath(path, HERE)} is out of date: run python3 build.py", file=sys.stderr)
                sys.exit(1)
        return
    for path, text in files.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
